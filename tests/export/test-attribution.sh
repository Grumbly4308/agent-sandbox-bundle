#!/usr/bin/env bash
# AI attribution is removed from commit messages by rewriting the commits in
# the clean repository, not merely reported. Human co-authors, authors, dates
# and file contents stay exactly as they were. What cannot be removed stops
# the export.

# shellcheck source=tests/export/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

fake_gitleaks 8.24.2 0
ROBOT=$(printf '\360\237\244\226')

SRC=$WORK/src
new_repo "$SRC"

echo "one" >"$SRC/one.txt"
git -C "$SRC" add -A
GIT_AUTHOR_DATE="2026-02-03T04:05:06+0200" git -C "$SRC" commit -q -F - <<EOF
Add the first file

It holds the word one.

$ROBOT Generated with [Claude Code](https://claude.ai/code)

Co-Authored-By: Claude <noreply@anthropic.com>
Co-authored-by: Jane Doe <jane@example.com>
EOF

echo "two" >"$SRC/two.txt"
commit_all "$SRC" "Add the second file, by hand"

echo "three" >"$SRC/three.txt"
git -C "$SRC" add -A
git -C "$SRC" commit -q -F - <<EOF
Add the third file

Generated by an assistant.
Written on behalf of the AI team.

Signed-off-by: Aiko Bottura <aiko@example.com>
CO-AUTHORED-BY:
  GitHub Copilot <copilot@users.noreply.github.com>
Co-authored-by: Rob Bothwell <rob@example.com>
Co-authored-by: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>
EOF
OLD_TIP=$(git -C "$SRC" rev-parse HEAD)
make_bundle "$SRC" "$WORK/attributed.bundle"

# --- stripped ---------------------------------------------------------------
next_session
run_export "$WORK/attributed.bundle" "$WORK/out" "$SESSION" "$BASE" work
assert_rc 0
assert_status "$SESSION_DIR" ATTRIBUTION stripped
REPO=$SESSION_DIR/repo.git
NEW_TIP=$(status_value "$SESSION_DIR" TIP)
if [ "$NEW_TIP" = "$OLD_TIP" ]; then fail "the tip did not change although messages were rewritten"; fi
assert_eq "$(clean_git "$REPO" rev-parse refs/heads/work)" "$NEW_TIP" "the branch in repo.git"
assert_has "tip $OLD_TIP -> $NEW_TIP"
assert_has "AI attribution was removed from 2 commit(s)"
assert_gitleaks_arg "--log-opts=$BASE..$NEW_TIP"

MESSAGES=$(clean_git "$REPO" log --format=%B "$BASE..$NEW_TIP")
for gone in "Claude" "anthropic" "Generated" "$ROBOT" "Copilot" "on behalf of" "dependabot"; do
  case $MESSAGES in
    *"$gone"*) fail "still in the commit messages: $gone" ;;
  esac
done
for kept in "Co-authored-by: Jane Doe <jane@example.com>" "Signed-off-by: Aiko Bottura <aiko@example.com>" \
  "Co-authored-by: Rob Bothwell <rob@example.com>" "It holds the word one." "Add the second file, by hand"; do
  case $MESSAGES in
    *"$kept"*) ;;
    *) fail "removed from the commit messages, and should not have been: $kept" ;;
  esac
done
assert_eq "$(clean_git "$REPO" log -1 --format=%B "$NEW_TIP~2")" "Add the first file

It holds the word one.

Co-authored-by: Jane Doe <jane@example.com>" "the first message after stripping"
ok "attribution lines are removed; human co-authors and the rest of the message are kept"

# Everything except the message is carried over byte for byte.
FIELDS='%an|%ae|%ad|%cn|%ce|%cd|%T'
assert_eq "$(clean_git "$REPO" log --date=raw --format="$FIELDS" "$BASE..$NEW_TIP")" \
  "$(git -C "$SRC" log --date=raw --format="$FIELDS" "$BASE..$OLD_TIP")" "authors, dates and trees"
assert_eq "$(clean_git "$REPO" rev-parse "$NEW_TIP~3")" "$BASE" "the commit below the rewritten ones"
clean_git "$REPO" fsck --strict --no-dangling >/dev/null 2>&1 || fail "the rewritten commits do not pass git fsck"
ok "tree, parents, author, committer and dates are preserved"

# --- exporting the result again finds nothing to strip ----------------------
git --git-dir="$REPO" bundle create -q "$WORK/stripped.bundle" work
next_session
run_export "$WORK/stripped.bundle" "$WORK/out" "$SESSION" "$BASE" work
assert_rc 0
assert_status "$SESSION_DIR" ATTRIBUTION clean
assert_status "$SESSION_DIR" TIP "$NEW_TIP"
assert_has "No AI attribution in the commit messages."
ok "a second export of the stripped commits is clean and changes no commit id"

# --- attribution below the starting commit is not this session's ------------
OLD=$WORK/old
git init -q -b work "$OLD"
echo "x" >"$OLD/x.txt"
git -C "$OLD" add -A
git -C "$OLD" commit -q -m "Earlier work" -m "Co-Authored-By: Claude <noreply@anthropic.com>"
OLD_BASE=$(git -C "$OLD" rev-parse HEAD)
echo "y" >"$OLD/y.txt"
commit_all "$OLD" "This session"
make_bundle "$OLD" "$WORK/old.bundle"
next_session
run_export "$WORK/old.bundle" "$WORK/out" "$SESSION" "$OLD_BASE" work
assert_rc 0
assert_status "$SESSION_DIR" ATTRIBUTION clean
assert_status "$SESSION_DIR" TIP "$(git -C "$OLD" rev-parse HEAD)"
ok "commits at or below the starting commit are never rewritten"

# --- an AI as the author cannot be stripped: refuse -------------------------
BOT=$WORK/bot
new_repo "$BOT"
echo "z" >"$BOT/z.txt"
git -C "$BOT" add -A
GIT_AUTHOR_NAME="Claude" GIT_AUTHOR_EMAIL="noreply@anthropic.com" git -C "$BOT" commit -q -m "Add z"
BOT_TIP=$(git -C "$BOT" rev-parse HEAD)
make_bundle "$BOT" "$WORK/bot.bundle"
next_session
run_export "$WORK/bot.bundle" "$WORK/out" "$SESSION" "$BASE" work
assert_rc 2
assert_status "$SESSION_DIR" ATTRIBUTION refused
assert_status "$SESSION_DIR" SCAN passed
assert_status "$SESSION_DIR" TIP "$BOT_TIP"
assert_has "name an AI as author or committer"
assert_has "push and pr will refuse"
ok "an AI author identity gives ATTRIBUTION=refused and status 2"

# --- a signature over the old message is dropped, not left invalid ----------
SIG=$WORK/sig
new_repo "$SIG"
tree=$(git -C "$SIG" rev-parse "HEAD^{tree}")
signed=$(printf 'tree %s\nparent %s\nauthor Test Human <human@example.com> 1700000000 +0000\ncommitter Test Human <human@example.com> 1700000000 +0000\ngpgsig -----BEGIN PGP SIGNATURE-----\n \n abcdef\n -----END PGP SIGNATURE-----\n\nSigned change\n\nCo-Authored-By: Codex <noreply@openai.com>\n' \
  "$tree" "$BASE" | git -C "$SIG" hash-object -t commit -w --stdin)
git -C "$SIG" update-ref refs/heads/work "$signed"
make_bundle "$SIG" "$WORK/sig.bundle"
next_session
run_export "$WORK/sig.bundle" "$WORK/out" "$SESSION" "$BASE" work
assert_rc 0
assert_status "$SESSION_DIR" ATTRIBUTION stripped
RAW=$(clean_git "$SESSION_DIR/repo.git" cat-file commit "$(status_value "$SESSION_DIR" TIP)")
case $RAW in
  *gpgsig* | *Codex*) fail "the rewritten commit still has the old signature or the trailer" ;;
esac
assert_eq "$(clean_git "$SESSION_DIR/repo.git" log -1 --format=%B work)" "Signed change" "the signed commit's message"
ok "a rewritten commit loses the signature that no longer matches it"

echo "test-attribution: all passed"
